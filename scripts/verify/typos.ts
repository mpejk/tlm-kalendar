// Lists suspected typos in the old site's Croatian (never corrected, only listed) -> TYPOS.md.   npx tsx scripts/verify/typos.ts
// Three mechanical tests, no dictionary:
//  A. the same Latin row has two Croatian renderings that differ in one word by one or two letters (the rarer form is the suspect);
//  B. a word is repeated ("da da");
//  C. a word that occurs in one or two cells only, one letter away (not in the ending) from a word that occurs at least 25 times.
import fs from 'node:fs';
import path from 'node:path';

const root = 'data/golden/masses';
type Cell = { hr: string; la: string; page: string };
const cells: Cell[] = [];
for (const y of fs.readdirSync(root)) for (const f of fs.readdirSync(path.join(root, y))) {
  if (!f.endsWith('.json')) continue;
  const j = JSON.parse(fs.readFileSync(path.join(root, y, f), 'utf8'));
  for (const it of j.items ?? []) for (const r of it.rows ?? []) if (r.hr && r.la) cells.push({ hr: r.hr, la: r.la, page: f.replace('.json', '') });
}
const strip = (s: string) => s.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
const words = (s: string) => strip(s).split(/[^A-Za-zČĆĐŠŽčćđšžÀ-ÿ']+/).filter(Boolean);
const normLa = (s: string) => strip(s).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/æ/g, 'ae').replace(/œ/g, 'oe').replace(/j/g, 'i').replace(/[^a-z]+/g, ' ').trim();
function lev(a: string, b: string): number {
  if (Math.abs(a.length - b.length) > 2) return 9;
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return d[a.length][b.length];
}

// distinct Croatian cells, with the pages they stand on
const distinct = new Map<string, { n: number; page: string; la: string }>();
for (const c of cells) { const k = strip(c.hr); const e = distinct.get(k); if (e) e.n++; else distinct.set(k, { n: 1, page: c.page, la: c.la }); }
const freq = new Map<string, number>(); const cellsOf = new Map<string, Set<string>>();
for (const [k] of distinct) for (const w of new Set(words(k).map(x => x.toLowerCase()))) { freq.set(w, (freq.get(w) ?? 0) + 1); }
for (const [k, e] of distinct) for (const w of words(k)) { const lw = w.toLowerCase(); if ((freq.get(lw) ?? 0) <= 2) { if (!cellsOf.has(lw)) cellsOf.set(lw, new Set()); cellsOf.get(lw)!.add(e.page); } }

const md: string[] = ['# Suspected typos in the Croatian of the old site', '',
  'Generated by `npx tsx scripts/verify/typos.ts` from the harvested pages. The lists A–D are suspects found mechanically; those that are plainly typos have been corrected (section *Corrected* at the end gives every correction with the original reading), the rest are shown as tradicionalnamisa.com printed them. The tests are mechanical (no dictionary), so each list contains false alarms; they are sorted so that the likeliest come first.', '',
  'To correct one after checking it: add a `find` / `replace` entry to `data/tm/corrections.yaml` and run `npm run deploy`.', ''];

// A. one-word differences between renderings of the same Latin
const byLa = new Map<string, Map<string, { n: number; page: string }>>();
for (const c of cells) { const k = normLa(c.la); if (k.length < 12) continue; if (!byLa.has(k)) byLa.set(k, new Map()); const m = byLa.get(k)!; const h = strip(c.hr); const e = m.get(h); if (e) e.n++; else m.set(h, { n: 1, page: c.page }); }
const seenA = new Set<string>(); const A: { rare: string; common: string; nr: number; nc: number; page: string; ctx: string; score: number }[] = [];
for (const m of byLa.values()) {
  if (m.size < 2) continue; const arr = [...m.entries()];
  for (let i = 0; i < arr.length; i++) for (let j = i + 1; j < arr.length; j++) {
    const a = words(arr[i][0]), b = words(arr[j][0]); if (a.length !== b.length) continue;
    const diff: number[] = []; for (let k = 0; k < a.length && diff.length < 2; k++) if (a[k] !== b[k]) diff.push(k);
    if (diff.length !== 1) continue; const k = diff[0]; const x = a[k], y = b[k];
    if (x.toLowerCase() === y.toLowerCase()) continue; const dist = lev(x.toLowerCase(), y.toLowerCase()); if (dist > 2 || Math.min(x.length, y.length) < 4) continue;
    const fx = freq.get(x.toLowerCase()) ?? 0, fy = freq.get(y.toLowerCase()) ?? 0;
    const [rare, common, nr, nc, e] = fx <= fy ? [x, y, fx, fy, arr[i][1]] : [y, x, fy, fx, arr[j][1]];
    const key = rare + '|' + common; if (seenA.has(key)) continue; seenA.add(key);
    const src = fx <= fy ? a : b; A.push({ rare, common, nr, nc, page: e.page, ctx: src.slice(Math.max(0, k - 4), k + 5).join(' '), score: nc / Math.max(1, nr) });
  }
}
A.sort((p, q) => q.score - p.score);
md.push(`## A. Same Latin, two Croatian renderings that differ in one word by one or two letters (${A.length})`, '', 'The rarer form is listed first. Where both forms are common words (a different case or tense), it is a difference of wording, not a typo.', '',
  '| Suspect | Other rendering has | Cells with suspect / other | Page (example) | Context |', '| --- | --- | ---: | --- | --- |');
for (const a of A) md.push(`| ${a.rare} | ${a.common} | ${a.nr} / ${a.nc} | ${a.page} | … ${a.ctx} … |`);
md.push('');

// B. repeated words
const B: string[] = [];
for (const [k, e] of distinct) { const m = strip(k).match(/(?<![\p{L}])(\p{L}{2,}) \1(?![\p{L}])/iu); if (m && !/^(sveti?|svet|amen|aleluja|gospodine|kyrie|hosana|jao|blago)$/i.test(m[1])) { const i = k.indexOf(m[0]); B.push(`- ${e.page}: «… ${k.slice(Math.max(0, i - 40), i + m[0].length + 40)} …»`); } }
md.push(`## B. Repeated word (${B.length})`, '', ...B, '');

// C. rare words one letter from a frequent word
const frequent = [...freq.entries()].filter(([w, n]) => n >= 25 && w.length >= 6);
const byLen = new Map<number, [string, number][]>(); for (const f of frequent) { if (!byLen.has(f[0].length)) byLen.set(f[0].length, []); byLen.get(f[0].length)!.push(f); }
const C: { w: string; near: string; n: number; page: string; dia: boolean }[] = [];
const fold = (s: string) => s.replace(/[čć]/g, 'c').replace(/đ/g, 'd').replace(/š/g, 's').replace(/ž/g, 'z');
for (const [w, pages] of cellsOf) {
  if (w.length < 6 || /['À-ÿ]/.test(w.replace(/[čćđšž]/g, ''))) continue;
  let best: [string, number] | null = null;
  for (const L of [w.length - 1, w.length, w.length + 1]) for (const f of byLen.get(L) ?? []) {
    if (lev(w, f[0]) !== 1) continue;
    // ignore differences in the last two letters (inflection)
    const stem = Math.min(w.length, f[0].length) - 2; if (w.slice(0, stem) === f[0].slice(0, stem)) continue;
    if (!best || f[1] > best[1]) best = f;
  }
  if (best) C.push({ w, near: best[0], n: best[1], page: [...pages][0], dia: fold(w) === fold(best[0]) });
}
C.sort((p, q) => Number(q.dia) - Number(p.dia) || q.n - p.n);
md.push(`## C. Rare word one letter away from a frequent word (${C.length})`, '', 'Occurs in at most two cells; the neighbour occurs in at least 25. Differences in the last two letters (endings) are ignored. Those differing only by a diacritic come first. Many of these are simply other words.', '',
  '| Rare word | Frequent neighbour (cells) | Page (example) |', '| --- | --- | --- |');
for (const c of C) md.push(`| ${c.w} | ${c.near} (${c.n}) | ${c.page} |`);
md.push('');

// D. characters that should not occur in Croatian text
const D: string[] = [];
for (const [k, e] of distinct) { const m = k.match(/[^\s\p{L}\p{N}.,;:!?()«»„”“"'’‘\-–—…\/\[\]*+℣℟✠†<>=&%°§|]/u) ?? k.match(/[æðèþÆÐÈÞ]/); if (m) { const i = k.indexOf(m[0]); D.push(`- ${e.page}: character «${m[0]}» in «… ${k.slice(Math.max(0, i - 30), i + 30)} …»`); } }
md.push(`## D. Unexpected characters (possible encoding damage left in the Croatian) (${D.length})`, '', ...(D.length ? D : ['None.']), '');

if (fs.existsSync('data/tm/kniewald-misprints.md')) md.push(fs.readFileSync('data/tm/kniewald-misprints.md', 'utf8').trim(), '');
md.push('## Latin typos on the old site', '', 'These were corrected against Divinum Officium (the site shows the Divinum Officium text). The individual cases with their pages are in `DIFFS.md` under "Mass texts, Latin" and in `data/verify/text-exceptions.yaml`; the count of sections that differ from the old site only in spelling or by such a typo is given there as well.', '');
// ---- corrected (after the review of November 2026): every correction with the original reading
{
  const YAML = (await import('yaml')).default;
  const cor = (YAML.parse(fs.readFileSync('data/tm/corrections.yaml', 'utf8')) ?? []) as any[];
  const pat = (YAML.parse(fs.readFileSync('data/corpus/patches.yaml', 'utf8')) ?? []) as any[];
  const one = (x: string) => String(x).replace(/\n/g, ' / ').replace(/\|/g, '\\|');
  md.push('## Corrected', '', 'Since the review of November 2026 obvious typos, wrong Scripture references and misplaced texts are corrected. The corrections are data, not code: `data/tm/corrections.yaml` (Croatian) and `data/corpus/patches.yaml` (Latin). Below is each one with the original reading. IDs beginning with T, H or R are findings of the review (ODGOVOR-NA-PROVJERU.md); TY are typos found in the lists above; L and A were found by comparing the Latin with the Missale Romanum 1962.', '',
    '### Croatian', '', '| ID | Original reading | Corrected | Note |', '| --- | --- | --- | --- |');
  for (const c of cor) md.push(c.find !== undefined ? `| ${c.id} | ${one(c.find)} | ${one(c.replace)} | ${one(c.why ?? '')} |` : `| ${c.id} | (the Croatian beside «${one(c.la).slice(0, 70)}…») | ${one(c.hr).slice(0, 160)}… | ${one(c.why ?? '')} ${c.source ? 'Izvor: ' + one(c.source) : ''} |`);
  md.push('', '### Latin (Mass formularies)', '', '| ID | Formulary, section | Original reading | Corrected | Checked against |', '| --- | --- | --- | --- | --- |');
  for (const p of pat) md.push(`| ${p.id} | ${p.formulary} ${p.section} | ${one(p.find)} | ${one(p.replace) || '(removed)'} | ${one(p.source ?? '')} |`);
  const rites = fs.readFileSync('scripts/build/rites.ts', 'utf8').match(/const LATIN_FIXES[^;]*;/s)?.[0] ?? '';
  const pairs = [...rites.matchAll(/\['([^']+)', '([^']+)'\]/g)].map(m => `| ${m[1]} | ${m[2]} |`);
  md.push('', '### Latin (rites: blessing of palms, Good Friday, Easter Vigil)', '', '| Original reading | Corrected |', '| --- | --- |', ...pairs, '');
}
fs.writeFileSync('TYPOS.md', md.join('\n'));
console.log({ cells: cells.length, distinct: distinct.size, A: A.length, B: B.length, C: C.length, D: D.length });
